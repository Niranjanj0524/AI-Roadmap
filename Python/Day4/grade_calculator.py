#Grade Calculator
marks = int(input("Enter marks : "))

if marks >= 90 and marks <= 100:
    print("Grade A")
elif marks >= 75 and marks <= 89:
    print("Grade B")
elif marks >= 50 and marks <= 74:
    print("Grade C")
elif marks >= 35 and marks <= 49:
    print("Grade D")
else:
    print("Fail")
