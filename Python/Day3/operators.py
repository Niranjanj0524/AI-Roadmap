# Floor Division Operator (//)
print(15 // 4)

# Addition Operator (+)
print(12 + 7)

# Subtraction Operator (-)
print(25 - 10)

# Multiplication Operator (*)
print(6 * 8)

# Division Operator (/)
print(20 / 4)

# Modulo Operator (%)
print(17 % 5)

# Exponentiation Operator (**)
print(9 ** 2)

# Equality Operator (==)
print(15 == 15)

# Inequality Operator (!=)
print(10 != 20)

# Greater Than Operator (>)
print(50 > 30)

# Less Than Operator (<)
print(12 < 45)

# Logical AND Operator (and) with Greater Than or Equal To (>=)
print((25 >= 18) and True)

# Logical OR Operator (or)
print(False or True)

# Logical NOT Operator (not)
print(not False)

# Addition Assignment Operator (+=)
score = 10
score += 5
print(score)

# Multiplication Assignment Operator (*=)
multiplier = 4
multiplier *= 3
print(multiplier)

# Membership Operator (in)
fruits = ["apple", "banana", "orange"]
print("banana" in fruits)

# Non-membership Operator (not in)
colors = ["red", "blue", "green"]
print("yellow" not in colors)

# Identity Operator (is)
list1 = [1, 2, 3]
list2 = list1
print(list1 is list2)

# Equality Operator (==) for structural comparison
list3 = [1, 2, 3]
list4 = [1, 2, 3]
print(list3 == list4)

# Multi-operator Program using Subtraction (-), Greater Than (>), and Logical AND (and)
price = 100
discount = 15
is_member = True
final_price = price - discount
give_bonus = (final_price > 80) and is_member
print(final_price)
print(give_bonus)
